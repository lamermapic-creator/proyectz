# Muestrea el diseño (diseno_mov.py, el mismo que se ve en Blender) y escribe scripts/jugador/movimientos.gd
# Uso: python3 a_gd_mov.py ../../../scripts/jugador/movimientos.gd   (o la ruta que sea)
import sys, os, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import diseno_mov as DM

N = 48     # muestras por ciclo
NU = 32    # muestras de las curvas del pie (u de 0 a 1, incluidos los dos extremos)


def fmt(xs):
	return "[" + ", ".join("%.5f" % x for x in xs) + "]"


salida = sys.argv[1]
L = []
L.append("class_name Movimientos")
L.append("## GENERADO por animaciones/blender/movimiento/a_gd_mov.py a partir de diseno_mov.py (el diseño que se ve en")
L.append("## Blender): NO editar a mano. Ciclos de la marcha (andar, correr, agachado) por fase φ = gait_ph / 2π:")
L.append("## pelvis (raiz_*: studs; pelvis_*: rad), cintura, cuello y brazo derecho (el izquierdo = medio ciclo después y")
L.append("## en espejo), y la forma del paso (pie_*: u = 0 despega, 1 apoya). Ver Animador._ciclo / _brazo_ciclo / _curva_pie.")
L.append("")
L.append("const N := %d" % N)
L.append("const NU := %d" % NU)
L.append("")
L.append("const CICLOS := {")
for c in DM.CICLOS:
	L.append('\t"%s": {' % c)
	for ch in DM.CANALES:
		L.append('\t\t"%s": %s,' % (ch, fmt([DM.canal(c, ch, k / N) for k in range(N)])))
	for ch in DM.CURVAS_PIE:
		L.append('\t\t"%s": %s,' % (ch, fmt([DM.pie(c, ch, k / (NU - 1)) for k in range(NU)])))
	L.append("\t},")
L.append("}")
L.append("")
L.append("## SALTO por fase t (0 despegue .. 1 a punto de aterrizar): ver diseno_mov.SALTO")
L.append("const SALTOS := {")
for c in DM.SALTO:
	L.append('\t"%s": {' % c)
	for ch in DM.SALTO[c]:
		L.append('\t\t"%s": %s,' % (ch, fmt([DM.salto(c, ch, k / (NU - 1)) for k in range(NU)])))
	L.append("\t},")
L.append("}")
L.append("")
L.append("## CUERPO A TIERRA: tumbarse por pb (0 de pie .. 1 tumbado) y ciclo de reptar por fase (ver diseno_mov)")
L.append("const TUMBAR := {")
for ch in DM.TUMBAR:
	L.append('\t"%s": %s,' % (ch, fmt([DM.tumbar(ch, k / (NU - 1)) for k in range(NU)])))
L.append("}")
L.append("const REPTAR := {")
for ch in DM.REPTAR:
	L.append('\t"%s": %s,' % (ch, fmt([DM.reptar(ch, k / N) for k in range(N)])))
L.append("}")
L.append("")
L.append("")
L.append("## COLGADO de una cornisa: q_* quieto (fase = tiempo / 2,8 s), m_* moviéndose (fase del paso de manos)")
L.append("const COLGADO := {")
for ch in DM.COLGADO:
	L.append('\t"%s": %s,' % (ch, fmt([DM.colgado(ch, k / N) for k in range(N)])))
L.append("}")
L.append("")
L.append("")
L.append("static func colgado(canal: String, phi: float) -> float:")
L.append("\tvar a: Array = COLGADO[canal]")
L.append("\tvar x := fposmod(phi, 1.0) * N")
L.append("\tvar i := int(x) % N")
L.append("\treturn lerpf(a[i], a[(i + 1) % N], x - floorf(x))")
L.append("")
L.append("")
L.append("## SORTEAR obstáculos (vallas y encaramarse), por el progreso p (0..1): ver diseno_mov.SORTEAR")
L.append("const SORTEAR := {")
for ch in DM.SORTEAR:
	L.append('\t"%s": %s,' % (ch, fmt([DM.sortear(ch, k / (NU - 1)) for k in range(NU)])))
L.append("}")
L.append("")
L.append("")
L.append("static func sortear(canal: String, p: float) -> float:")
L.append("\tvar a: Array = SORTEAR[canal]")
L.append("\tvar x := clampf(p, 0.0, 1.0) * (NU - 1)")
L.append("\tvar i := mini(int(x), NU - 2)")
L.append("\treturn lerpf(a[i], a[i + 1], x - i)")
L.append("")
L.append("")
L.append("static func tumbar(canal: String, pb: float) -> float:")
L.append("\tvar a: Array = TUMBAR[canal]")
L.append("\tvar x := clampf(pb, 0.0, 1.0) * (NU - 1)")
L.append("\tvar i := mini(int(x), NU - 2)")
L.append("\treturn lerpf(a[i], a[i + 1], x - i)")
L.append("")
L.append("")
L.append("static func reptar(canal: String, phi: float) -> float:")
L.append("\tvar a: Array = REPTAR[canal]")
L.append("\tvar x := fposmod(phi, 1.0) * N")
L.append("\tvar i := int(x) % N")
L.append("\treturn lerpf(a[i], a[(i + 1) % N], x - floorf(x))")
L.append("")
L.append("")
L.append("static func salto(tipo: String, canal: String, t: float) -> float:")
L.append("\tvar a: Array = SALTOS[tipo][canal]")
L.append("\tvar x := clampf(t, 0.0, 1.0) * (NU - 1)")
L.append("\tvar i := mini(int(x), NU - 2)")
L.append("\treturn lerpf(a[i], a[i + 1], x - i)")
L.append("")
L.append("")
L.append("## valor de un canal del ciclo en la fase phi (0..1, periódica), interpolación lineal entre muestras")
L.append("static func ciclo(nombre: String, canal: String, phi: float) -> float:")
L.append("\tvar a: Array = CICLOS[nombre][canal]")
L.append("\tvar x := fposmod(phi, 1.0) * N")
L.append("\tvar i := int(x) % N")
L.append("\treturn lerpf(a[i], a[(i + 1) % N], x - floorf(x))")
L.append("")
L.append("")
L.append("## curva del pie (u de 0 a 1)")
L.append("static func pie(nombre: String, canal: String, u: float) -> float:")
L.append("\tvar a: Array = CICLOS[nombre][canal]")
L.append("\tvar x := clampf(u, 0.0, 1.0) * (NU - 1)")
L.append("\tvar i := mini(int(x), NU - 2)")
L.append("\treturn lerpf(a[i], a[i + 1], x - i)")
L.append("")
open(salida, "w").write("\n".join(L))
print("ESCRITO", salida)
